#!/usr/bin/env python3
"""
Independent computational verification for Conjecture 00000000592.

Verifies:
1. Primary counterexample S = <4, 6, 7, 9> (1D Cohen-Macaulay numerical semigroup ring k[S],
   embedding dimension 4, genus 4, multiplicity 4, Frobenius number 5, type 3):
   - Direct computation of PF(S) = {2, 3, 5}, H^1_m(k[S]) socle, and the Goto-Watanabe
     graded canonical module omega_{k[S]} = oplus_{-d notin S} k * t^d;
   - Independent homological computation of graded Betti numbers beta_{i,j}(k[S]) over
     P = k[x_1, x_2, x_3, x_4] (weights 4, 6, 7, 9) via exact rational Koszul homology,
     confirming Ext^3_P(k[S], P(-26)) has minimal generator degrees {-5, -3, -2} = -PF(S);
   - Proof that {-5, -3, -2} != {2 + c, 3 + c, 5 + c} for all c in Z (gap vector (2,1) != (1,2)).
2. Exhaustive audit of numerical semigroups up to genus 6 and arithmetic-progression families:
   - Confirms 0 counterexamples for genus <= 3, multiplicity <= 3, Frobenius <= 4,
     embedding dimension <= 3, and 4-generator arithmetic progressions, explaining why small
     or structured test suites satisfy -PF(S) = PF(S) + c while S = <4, 6, 7, 9> is the unique
     genus-4 counterexample.
3. Higher-Krull-dimension Cohen-Macaulay extensions k[S x N^{d-1}] for d = 1..5.
4. Non-Cohen-Macaulay 2D standard Z-graded affine semigroup counterexample:
   Macaulay's smooth rational quartic curve S_Mac = <(4,0), (3,1), (1,3), (0,4)> ~=
   <(1,0), (1,1), (1,3), (1,4)>, where type(R) = |PF(S_Mac)| = 1 while mu_R(omega_R) = 3 != 1.
"""

from fractions import Fraction
from functools import reduce
from itertools import combinations
from math import gcd
import sys


def exact_rank(matrix: list[list[int]]) -> int:
    """Compute exact rank over Q using Gaussian elimination with Fractions."""
    if not matrix or not matrix[0]:
        return 0
    rows = len(matrix)
    cols = len(matrix[0])
    a = [[Fraction(x) for x in row] for row in matrix]
    r = 0
    for c in range(cols):
        piv = None
        for i in range(r, rows):
            if a[i][c] != 0:
                piv = i
                break
        if piv is None:
            continue
        a[r], a[piv] = a[piv], a[r]
        inv_val = Fraction(1, 1) / a[r][c]
        for j in range(c, cols):
            a[r][j] *= inv_val
        for i in range(rows):
            if i != r and a[i][c] != 0:
                fac = a[i][c]
                for j in range(c, cols):
                    a[i][j] -= fac * a[r][j]
        r += 1
    return r


def numerical_semigroup_data(gens: list[int]) -> dict:
    """Compute canonical invariants of a numerical semigroup generated by gens."""
    assert all(g > 0 for g in gens), "Generators must be positive integers"
    assert reduce(gcd, gens) == 1, "Generators must be coprime"
    bound = max(gens) * min(gens) * 2 + 50
    in_s = [False] * (bound + 1)
    in_s[0] = True
    for x in range(bound + 1):
        if in_s[x]:
            for g in gens:
                if x + g <= bound:
                    in_s[x + g] = True

    min_gens = [
        g
        for g in sorted(set(gens))
        if not any(in_s[a] and in_s[g - a] for a in range(1, g))
    ]
    gaps = [x for x in range(bound + 1) if not in_s[x]]
    frob = max(gaps) if gaps else -1
    assert frob + min(min_gens) < bound, "Conductor bound too small"

    # Pseudo-Frobenius numbers: x in Z \ S with x + s in S for all s in S \ {0}
    pf = []
    for x in range(-max(min_gens) - 5, frob + 1):
        if x >= 0 and in_s[x]:
            continue
        # Checking x + s in S for all s in S \ {0} is equivalent to checking minimal generators:
        # verify BOTH against all minimal generators AND all s in S \ {0} up to bound.
        ok_gens = all((x + g >= 0 and (x + g > frob or in_s[x + g])) for g in min_gens)
        if ok_gens:
            for s in range(1, frob + max(min_gens) + 5):
                if s > frob or in_s[s]:
                    val = x + s
                    assert val >= 0 and (val > frob or in_s[val])
            pf.append(x)

    # Direct computation of Goto-Watanabe canonical module omega_{k[S]} = oplus_{-d notin S} k * t^d
    # Truncate at a safe window [-frob - 5, frob + 2 * max(min_gens) + 10]; note omega_d = 0 for d < -frob.
    low_deg = -frob - 5
    high_deg = frob + 2 * max(min_gens) + 10

    def in_semigroup(n: int) -> bool:
        return n >= 0 and (n > frob or in_s[n])

    omega_degs = {d for d in range(low_deg, high_deg + 1) if not in_semigroup(-d)}
    assert all(d >= -frob for d in omega_degs)

    # Verify S-submodule closure: d in omega, s in S => d + s in omega
    for d in list(omega_degs):
        for g in min_gens:
            if d + g <= high_deg:
                assert (d + g) in omega_degs

    # Compute m * omega where m = oplus_{s in S \ {0}} k * t^s
    pos_s = [s for s in range(1, high_deg - low_deg + 1) if in_semigroup(s)]
    m_omega_degs = set()
    for d in omega_degs:
        for s in pos_s:
            if d + s <= high_deg:
                m_omega_degs.add(d + s)

    # Minimal homogeneous generator degrees = support of omega / m*omega
    min_omega_gen_degs = sorted(d for d in omega_degs if d not in m_omega_degs)
    return {
        "min_gens": min_gens,
        "edim": len(min_gens),
        "multiplicity": min(min_gens),
        "gaps": gaps,
        "genus": len(gaps),
        "frobenius": frob,
        "pf": pf,
        "type": len(pf),
        "omega_min_gen_degs": min_omega_gen_degs,
    }


def is_shifted_copy(deg_set: list[int], pf_set: list[int]) -> tuple[bool, int | None]:
    """Check whether sorted deg_set equals {f + c : f in pf_set} for some c in Z."""
    if len(deg_set) != len(pf_set):
        return False, None
    if not deg_set:
        return True, 0
    c = deg_set[0] - pf_set[0]
    if deg_set == sorted(f + c for f in pf_set):
        return True, c
    return False, None


def verify_primary_counterexample() -> None:
    print("[1/4] Verifying primary counterexample S = <4, 6, 7, 9> ...")
    info = numerical_semigroup_data([4, 6, 7, 9])
    assert info["min_gens"] == [4, 6, 7, 9]
    assert info["edim"] == 4
    assert info["multiplicity"] == 4
    assert info["gaps"] == [1, 2, 3, 5]
    assert info["genus"] == 4
    assert info["frobenius"] == 5
    assert info["pf"] == [2, 3, 5]
    assert info["type"] == 3
    assert info["omega_min_gen_degs"] == [-5, -3, -2]

    aligned, _ = is_shifted_copy(info["omega_min_gen_degs"], info["pf"])
    assert not aligned, "Expected S = <4, 6, 7, 9> to refute PF + c alignment"

    # Independent Koszul homology verification of Ext^3_P(k[S], P(-26))
    weights = [4, 6, 7, 9]
    weight_sum = sum(weights)
    assert weight_sum == 26
    gaps_set = set(info["gaps"])

    def in_s(n: int) -> bool:
        return n >= 0 and n not in gaps_set

    betti: dict[int, list[int]] = {0: [], 1: [], 2: [], 3: [], 4: []}
    for d in range(0, 40):
        bases = {
            i: [J for J in combinations(range(4), i) if in_s(d - sum(weights[j] for j in J))]
            for i in range(5)
        }
        ranks = {0: 0, 5: 0}
        for i in range(1, 5):
            dom = bases[i]
            cod = bases[i - 1]
            cod_idx = {J: idx for idx, J in enumerate(cod)}
            mat = [[0] * len(dom) for _ in range(len(cod))]
            for col, J in enumerate(dom):
                for pos, j in enumerate(J):
                    j_sub = J[:pos] + J[pos + 1 :]
                    mat[cod_idx[j_sub]][col] += (-1) ** pos
            ranks[i] = exact_rank(mat)
        for i in range(5):
            h_dim = len(bases[i]) - ranks[i] - ranks[i + 1]
            if h_dim > 0:
                betti[i].extend([d] * h_dim)

    assert betti[0] == [0]
    assert betti[1] == [12, 13, 14, 15, 16, 18]
    assert betti[2] == [19, 20, 21, 22, 22, 23, 24, 25]
    assert betti[3] == [28, 29, 31]
    assert betti[4] == []

    # Verify Hilbert series numerator identity up to degree 60
    max_deg = 60
    hilb = [1 if in_s(n) else 0 for n in range(max_deg + 1)]
    for w in weights:
        new_hilb = list(hilb)
        for n in range(w, max_deg + 1):
            new_hilb[n] -= hilb[n - w]
        hilb = new_hilb

    expected_num = [0] * (max_deg + 1)
    for i in range(5):
        sign = (-1) ** i
        for b in betti[i]:
            if b <= max_deg:
                expected_num[b] += sign
    assert hilb == expected_num, "Hilbert series numerator mismatch"

    ext3_gen_degs = sorted(weight_sum - b for b in betti[3])
    assert ext3_gen_degs == [-5, -3, -2]
    print(
        f"      PASS: S = <4, 6, 7, 9> has edim=4, genus=4, type=3, PF={info['pf']}, "
        f"Deg_min(omega)={ext3_gen_degs} (Koszul top twists {betti[3]}), gap vector (2,1) != (1,2)."
    )


def verify_genus_and_special_regimes() -> None:
    print("[2/4] Auditing genus <= 6 tree, edim <= 3, and 4-generator arithmetic progressions ...")
    tree: dict[int, list[frozenset[int]]] = {0: [frozenset()]}
    for g in range(6):
        tree[g + 1] = []
        for gaps in tree[g]:
            frob = max(gaps) if gaps else 0
            for x in range(frob + 1, 2 * (g + 1) + 3):
                if x not in gaps and all(
                    (a in gaps) or ((x - a) in gaps) for a in range(1, x)
                ):
                    tree[g + 1].append(gaps | {x})

    expected_counts = {0: 1, 1: 1, 2: 2, 3: 4, 4: 7, 5: 12, 6: 23}
    for g, gap_sets in tree.items():
        assert len(gap_sets) == expected_counts[g]
        cex = []
        for gaps in gap_sets:
            if not gaps:
                pf = [-1]
                min_gens = [1]
                frob = -1
            else:
                frob = max(gaps)
                min_gens = [
                    x
                    for x in range(1, frob + 15)
                    if x not in gaps
                    and all((a in gaps) or ((x - a) in gaps) for a in range(1, x))
                ]
                pf = [x for x in sorted(gaps) if all((x + s) not in gaps for s in min_gens)]
            omega_degs = sorted(-f for f in pf)
            ok, _ = is_shifted_copy(omega_degs, pf)
            if len( min_gens ) <= 3:
                assert len(pf) <= 2 and ok, "Herzog bound / type <= 2 alignment violated"
            if frob <= 4 or min(min_gens) <= 3:
                assert ok, "Expected alignment to hold for Frobenius <= 4 and multiplicity <= 3"
            if not ok:
                cex.append((sorted(gaps), min_gens, pf))
        if g <= 3:
            assert len(cex) == 0
        elif g == 4:
            assert len(cex) == 1 and cex[0][1] == [4, 6, 7, 9]

    ap_checked = 0
    for a in range(4, 26):
        for diff in range(1, 11):
            if gcd(a, diff) == 1:
                info = numerical_semigroup_data([a, a + diff, a + 2 * diff, a + 3 * diff])
                if info["edim"] == 4:
                    ap_checked += 1
                    ok, _ = is_shifted_copy(info["omega_min_gen_degs"], info["pf"])
                    assert ok, "Arithmetic-progression semigroup must have symmetric PF"
    assert ap_checked > 100
    print(
        f"      PASS: 50 semigroups up to genus 6 checked (unique g=4 counterexample <4,6,7,9>); "
        f"{ap_checked} four-generator arithmetic progressions all satisfy alignment."
    )


def verify_higher_dim_cm_extensions() -> None:
    print("[3/4] Verifying higher-Krull-dimension Cohen-Macaulay semigroup rings k[S x N^{d-1}] ...")
    base_pf = [2, 3, 5]
    for krull_dim in range(1, 6):
        # Adjoining (d-1) polynomial variables of degree 1 shifts omega_P by -(d-1),
        # so omega_{R[y_1..y_{d-1}]} = omega_R otimes k[y_1..y_{d-1}](-(d-1)) has
        # minimal generator degrees -PF(S) + (d - 1).
        omega_degs = sorted(-f + (krull_dim - 1) for f in base_pf)
        ok, _ = is_shifted_copy(omega_degs, base_pf)
        assert not ok
        gaps_vec = [omega_degs[i + 1] - omega_degs[i] for i in range(len(omega_degs) - 1)]
        assert gaps_vec == [2, 1]
    print("      PASS: Krull dimensions d = 1..5 all retain asymmetric gap vector (2, 1) != (1, 2).")


def verify_macaulay_non_cm_counterexample() -> None:
    print("[4/4] Verifying non-Cohen-Macaulay 2D semigroup ring (Macaulay's quartic curve) ...")
    gens = [(1, 0), (1, 1), (1, 3), (1, 4)]

    def in_smac(d: int, b: int) -> bool:
        if d < 0:
            return False
        if d == 0:
            return b == 0
        if d == 1:
            return b in (0, 1, 3, 4)
        return 0 <= b <= 4 * d

    # Verify PF(S_Mac) in Z^2 \ S_Mac
    pf_mac = [
        (d, b)
        for d in range(-4, 8)
        for b in range(-16, 35)
        if not in_smac(d, b) and all(in_smac(d + gd, b + gb) for gd, gb in gens)
    ]
    assert pf_mac == [(1, 2)]

    # Verify Danilov-Stanley / Matlis canonical module minimal generators
    omega_pts = {(d, b) for d in range(1, 7) for b in range(1, 4 * d)}
    omega_min_gens = sorted(
        (d, b)
        for (d, b) in omega_pts
        if not any((d - gd, b - gb) in omega_pts for gd, gb in gens)
    )
    assert omega_min_gens == [(1, 1), (1, 2), (1, 3)]
    assert len(omega_min_gens) == 3 and len(pf_mac) == 1

    # Verify bigraded Koszul Betti numbers over P = k[z0, z1, z3, z4]
    betti_mac: dict[int, list[tuple[int, int]]] = {0: [], 1: [], 2: [], 3: [], 4: []}
    for d in range(0, 7):
        for b in range(0, 4 * d + 1):
            bases = {
                i: [
                    J
                    for J in combinations(range(4), i)
                    if in_smac(d - i, b - sum(gens[j][1] for j in J))
                ]
                for i in range(5)
            }
            ranks = {0: 0, 5: 0}
            for i in range(1, 5):
                dom = bases[i]
                cod = bases[i - 1]
                if not dom or not cod:
                    ranks[i] = 0
                    continue
                cod_idx = {J: idx for idx, J in enumerate(cod)}
                mat = [[0] * len(dom) for _ in range(len(cod))]
                for col, J in enumerate(dom):
                    for pos, j in enumerate(J):
                        j_sub = J[:pos] + J[pos + 1 :]
                        mat[cod_idx[j_sub]][col] += (-1) ** pos
                ranks[i] = exact_rank(mat)
            for i in range(5):
                h_dim = len(bases[i]) - ranks[i] - ranks[i + 1]
                if h_dim > 0:
                    betti_mac[i].extend([(d, b)] * h_dim)

    assert len(betti_mac[0]) == 1
    assert len(betti_mac[1]) == 4
    assert len(betti_mac[2]) == 4
    assert len(betti_mac[3]) == 1
    assert len(betti_mac[4]) == 0
    # Auslander-Buchsbaum: depth(R) = dim(P) - pdim_P(R) = 4 - 3 = 1 < 2 = dim(R)
    pdim = max(i for i in range(5) if betti_mac[i])
    depth_r = 4 - pdim
    assert depth_r == 1
    print(
        f"      PASS: Macaulay semigroup has dim=2, depth={depth_r}, PF={pf_mac} (type=1), "
        f"while omega_R has {len(omega_min_gens)} minimal generators {omega_min_gens} (3 != 1)."
    )


def main() -> int:
    print("=== Conjecture 00000000592 Verification Suite ===")
    verify_primary_counterexample()
    verify_genus_and_special_regimes()
    verify_higher_dim_cm_extensions()
    verify_macaulay_non_cm_counterexample()
    print("=== ALL CHECKS PASSED (EXIT 0) ===")
    return 0


if __name__ == "__main__":
    sys.exit(main())
