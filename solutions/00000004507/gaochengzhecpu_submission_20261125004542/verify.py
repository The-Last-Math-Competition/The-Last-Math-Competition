#!/usr/bin/env python3
"""
Independent computational verification for Conjecture 00000004507:
"Definition: A Galois connection is a monotone adjoint pair between posets.
 Conjecture: The minimal representation of its inverse is a closure system
 generated by units, the representation length is an explicit count of units,
 and finite lattices attain the lower bound 2."

This script exhaustively tests all standard mathematical interpretations of:
  1. Monotone Galois connections (f, g) : P <-> Q and their Galois inverses;
  2. Unlabeled finite lattices up to |L| <= 7 (verifying OEIS A006966 counts
     1, 1, 1, 2, 5, 15, 53) and all closure systems on finite lattices;
  3. Brute-force minimal generating / representation lengths under Readings I-IV:
     - Reading I:   Minimal meet-generating set M(C) under arbitrary meets;
     - Reading II:  Minimal ground-set size |U| for set-closure systems in P(U);
     - Reading III: Minimal nonempty-meet generating set M(C) U {top} and |C|;
     - Reading IV:  Minimal unit-implicational basis Sigma_min on P(U);
  4. General poset (antichain A_2) and dense dyadic cut diagnostics.

Exits with status 0 iff every mathematical assertion and counterexample check passes.
"""

from __future__ import annotations

import itertools
import sys
from dataclasses import dataclass
from typing import Dict, FrozenSet, Iterable, List, Optional, Sequence, Set, Tuple


@dataclass(frozen=True)
class FinitePoset:
    name: str
    n: int
    # leq[x][y] is True iff x <= y
    leq: Tuple[Tuple[bool, ...], ...]

    def is_valid_poset(self) -> bool:
        for x in range(self.n):
            if not self.leq[x][x]:
                return False
        for x in range(self.n):
            for y in range(self.n):
                if self.leq[x][y] and self.leq[y][x] and x != y:
                    return False
                for z in range(self.n):
                    if self.leq[x][y] and self.leq[y][z] and not self.leq[x][z]:
                        return False
        return True

    def dual(self) -> "FinitePoset":
        dual_leq = tuple(
            tuple(self.leq[y][x] for y in range(self.n))
            for x in range(self.n)
        )
        return FinitePoset(name=f"{self.name}^op", n=self.n, leq=dual_leq)

    def meet_of_subset(self, subset: Iterable[int]) -> Optional[int]:
        elems = list(subset)
        lower_bounds = [
            z for z in range(self.n) if all(self.leq[z][s] for s in elems)
        ]
        for lb in lower_bounds:
            if all(self.leq[other][lb] for other in lower_bounds):
                return lb
        return None

    def join_of_subset(self, subset: Iterable[int]) -> Optional[int]:
        elems = list(subset)
        upper_bounds = [
            z for z in range(self.n) if all(self.leq[s][z] for s in elems)
        ]
        for ub in upper_bounds:
            if all(self.leq[ub][other] for other in upper_bounds):
                return ub
        return None

    def is_finite_lattice(self) -> bool:
        if self.n == 0 or not self.is_valid_poset():
            return False
        if self.meet_of_subset(()) is None or self.join_of_subset(()) is None:
            return False
        for x in range(self.n):
            for y in range(self.n):
                if self.meet_of_subset((x, y)) is None:
                    return False
                if self.join_of_subset((x, y)) is None:
                    return False
        return True

    def top(self) -> int:
        t = self.meet_of_subset(())
        assert t is not None
        return t

    def bot(self) -> int:
        b = self.join_of_subset(())
        assert b is not None
        return b

    def meet(self, x: int, y: int) -> int:
        m = self.meet_of_subset((x, y))
        assert m is not None
        return m

    def join(self, x: int, y: int) -> int:
        j = self.join_of_subset((x, y))
        assert j is not None
        return j


def make_chain(n: int) -> FinitePoset:
    leq = tuple(tuple(x <= y for y in range(n)) for x in range(n))
    return FinitePoset(name=f"C_{n}", n=n, leq=leq)


def make_boolean(k: int) -> FinitePoset:
    n = 1 << k
    leq = tuple(tuple((x & y) == x for y in range(n)) for x in range(n))
    return FinitePoset(name=f"B_{k}", n=n, leq=leq)


def make_antichain(n: int) -> FinitePoset:
    leq = tuple(tuple(x == y for y in range(n)) for x in range(n))
    return FinitePoset(name=f"A_{n}", n=n, leq=leq)


def canonical_certificate(leq: Tuple[Tuple[bool, ...], ...]) -> Tuple[int, ...]:
    """Canonical isomorphism invariant for small posets via topological permutations."""
    n = len(leq)
    in_deg = [sum(1 for x in range(n) if x != y and leq[x][y]) for y in range(n)]
    out_deg = [sum(1 for y in range(n) if x != y and leq[x][y]) for x in range(n)]
    # Group vertices by (in_deg, out_deg) signature to prune permutations cleanly
    groups: Dict[Tuple[int, int], List[int]] = {}
    for v in range(n):
        sig = (in_deg[v], out_deg[v])
        groups.setdefault(sig, []).append(v)
    ordered_sigs = sorted(groups.keys())
    group_lists = [groups[s] for s in ordered_sigs]

    best: Optional[Tuple[int, ...]] = None
    for prod in itertools.product(*(itertools.permutations(g) for g in group_lists)):
        perm = [v for block in prod for v in block]
        code = tuple(
            1 if leq[perm[i]][perm[j]] else 0
            for i in range(n)
            for j in range(n)
        )
        if best is None or code < best:
            best = code
    assert best is not None
    return best


def generate_unlabeled_lattices(n: int) -> List[FinitePoset]:
    """
    Generate all unlabeled finite lattices on n elements (0 = bottom, n-1 = top).
    Uses linear-extension indexing so x <= y implies x <= y as integers.
    """
    if n == 1:
        return [make_chain(1)]
    if n == 2:
        return [make_chain(2)]

    # Pairs (i, j) with 0 < i < j < n - 1 ordered by increasing gap j - i
    # so all intermediate pairs (i, k) and (k, j) are already decided.
    interior_pairs = sorted(
        [(i, j) for i in range(1, n - 1) for j in range(i + 1, n - 1)],
        key=lambda pair: (pair[1] - pair[0], pair[0]),
    )
    seen: Set[Tuple[int, ...]] = set()
    lattices: List[FinitePoset] = []

    # Backtrack over interior comparability Decisions enforcing transitivity
    num_pairs = len(interior_pairs)

    def backtrack(idx: int, mat: List[List[bool]]) -> None:
        if idx == num_pairs:
            leq = tuple(tuple(row) for row in mat)
            poset = FinitePoset(name=f"L_{n}_{len(lattices)}", n=n, leq=leq)
            if poset.is_finite_lattice():
                cert = canonical_certificate(leq)
                if cert not in seen:
                    seen.add(cert)
                    lattices.append(poset)
            return

        i, j = interior_pairs[idx]
        # Check if transitivity already forces mat[i][j] = True
        forced_true = any(mat[i][k] and mat[k][j] for k in range(i + 1, j))
        if forced_true:
            mat[i][j] = True
            backtrack(idx + 1, mat)
            mat[i][j] = False
        else:
            # Branch False
            mat[i][j] = False
            backtrack(idx + 1, mat)
            # Branch True
            mat[i][j] = True
            backtrack(idx + 1, mat)
            mat[i][j] = False

    init_mat = [[False] * n for _ in range(n)]
    for x in range(n):
        init_mat[x][x] = True
        init_mat[0][x] = True
        init_mat[x][n - 1] = True

    backtrack(0, init_mat)
    return lattices


def monotone_maps(P: FinitePoset, Q: FinitePoset) -> List[Tuple[int, ...]]:
    maps: List[Tuple[int, ...]] = []
    comp_pairs = [
        (x, y) for x in range(P.n) for y in range(P.n) if x != y and P.leq[x][y]
    ]
    for f in itertools.product(range(Q.n), repeat=P.n):
        if all(Q.leq[f[x]][f[y]] for x, y in comp_pairs):
            maps.append(f)
    return maps


def is_galois_connection(
    P: FinitePoset, Q: FinitePoset, f: Sequence[int], g: Sequence[int]
) -> bool:
    for x in range(P.n):
        for y in range(P.n):
            if P.leq[x][y] and not Q.leq[f[x]][f[y]]:
                return False
    for y1 in range(Q.n):
        for y2 in range(Q.n):
            if Q.leq[y1][y2] and not P.leq[g[y1]][g[y2]]:
                return False
    for x in range(P.n):
        for y in range(Q.n):
            if Q.leq[f[x]][y] != P.leq[x][g[y]]:
                return False
    return True


def enumerate_galois_connections(
    P: FinitePoset, Q: FinitePoset
) -> List[Tuple[Tuple[int, ...], Tuple[int, ...]]]:
    f_list = monotone_maps(P, Q)
    g_list = monotone_maps(Q, P)
    pairs: List[Tuple[Tuple[int, ...], Tuple[int, ...]]] = []
    for f in f_list:
        for g in g_list:
            if all(
                Q.leq[f[x]][y] == P.leq[x][g[y]]
                for x in range(P.n)
                for y in range(Q.n)
            ):
                pairs.append((f, g))
    return pairs


def closure_system_generated_by(
    L: FinitePoset, generators: Iterable[int], allow_empty_meet: bool = True
) -> FrozenSet[int]:
    gens = tuple(generators)
    result: Set[int] = set()
    start_r = 0 if allow_empty_meet else 1
    for r in range(start_r, len(gens) + 1):
        for sub in itertools.combinations(gens, r):
            m = L.meet_of_subset(sub)
            assert m is not None
            result.add(m)
    return frozenset(result)


def all_closure_systems(L: FinitePoset) -> List[FrozenSet[int]]:
    systems: Set[FrozenSet[int]] = set()
    top = L.top()
    other_elems = [x for x in range(L.n) if x != top]
    for r in range(len(other_elems) + 1):
        for sub in itertools.combinations(other_elems, r):
            cand = frozenset(sub) | {top}
            closed_ok = True
            for a in cand:
                for b in cand:
                    if L.meet(a, b) not in cand:
                        closed_ok = False
                        break
                if not closed_ok:
                    break
            if closed_ok:
                systems.add(cand)
    return sorted(systems, key=lambda s: (len(s), tuple(sorted(s))))


def meet_irreducibles_in_closure_system(
    L: FinitePoset, C: FrozenSet[int]
) -> FrozenSet[int]:
    top = L.top()
    irr: Set[int] = set()
    for m in C:
        if m == top:
            continue
        is_irr = True
        for a in C:
            for b in C:
                if L.meet(a, b) == m and m != a and m != b:
                    is_irr = False
                    break
            if not is_irr:
                break
        if is_irr:
            irr.add(m)
    return frozenset(irr)


def subposet_from_subset(L: FinitePoset, C: FrozenSet[int]) -> FinitePoset:
    elems = sorted(C)
    sub_leq = tuple(
        tuple(L.leq[elems[i]][elems[j]] for j in range(len(elems)))
        for i in range(len(elems))
    )
    return FinitePoset(name=f"{L.name}|_{elems}", n=len(elems), leq=sub_leq)


def join_irreducibles(L: FinitePoset) -> FrozenSet[int]:
    bot = L.bot()
    irr: Set[int] = set()
    for j in range(L.n):
        if j == bot:
            continue
        if all(
            L.join(a, b) != j or j == a or j == b
            for a in range(L.n)
            for b in range(L.n)
        ):
            irr.add(j)
    return frozenset(irr)


def brute_force_min_ground_set_size(target: FinitePoset) -> int:
    """
    Find minimum k >= 0 such that target is order-isomorphic to a closure system
    F <= P({0, ..., k-1}) closed under set intersections (including empty intersection = U).
    """
    target_cert = canonical_certificate(target.leq)
    for k in range(target.n + 1):
        full_mask = (1 << k) - 1
        # A closure system in P({0..k-1}) of size target.n must contain full_mask
        if target.n == 1:
            if k == 0:
                return 0
            continue
        candidates = [mask for mask in range(full_mask)]
        if len(candidates) < target.n - 1:
            continue
        for chosen in itertools.combinations(candidates, target.n - 1):
            fam = chosen + (full_mask,)
            fam_set = set(fam)
            # Check intersection closure
            if not all((a & b) in fam_set for a in fam for b in fam):
                continue
            fam_leq = tuple(
                tuple((fam[i] & fam[j]) == fam[i] for j in range(target.n))
                for i in range(target.n)
            )
            if canonical_certificate(fam_leq) == target_cert:
                return k
    raise RuntimeError(f"No concrete set-closure representation found for {target.name}")


def canonical_direct_unit_implications(
    k: int, family_masks: Set[int]
) -> List[Tuple[int, int]]:
    """
    Compute minimal non-redundant unit implications A -> {b} (b not in A) whose
    models equal family_masks <= P({0..k-1}), and return minimum basis size by
    brute force when small, or exact non-trivial implication emptiness check for P(U).
    """
    full_mask = (1 << k) - 1
    assert full_mask in family_masks
    for a in family_masks:
        for b in family_masks:
            assert (a & b) in family_masks

    def cl(mask: int) -> int:
        res = full_mask
        for c in family_masks:
            if (mask & c) == mask:
                res &= c
        return res

    # Valid unit implications A -> b with b in cl(A) \ A and A premise-minimal
    minimal_unit_imps: List[Tuple[int, int]] = []
    for mask in range(1 << k):
        c_mask = cl(mask)
        added = c_mask & ~mask
        if added == 0:
            continue
        # Check if any proper subset already implies b
        for b in range(k):
            if (added >> b) & 1:
                if all(
                    not (((cl(mask & ~(1 << a)) >> b) & 1))
                    for a in range(k)
                    if (mask >> a) & 1
                ):
                    minimal_unit_imps.append((mask, b))
    return minimal_unit_imps


def verify_all() -> None:
    print("=== Conjecture 00000004507 Computational Verification ===")

    # 1. Enumerate unlabeled finite lattices for n = 1..7 and verify OEIS A006966
    expected_oeis_a006966 = {1: 1, 2: 1, 3: 1, 4: 2, 5: 5, 6: 15, 7: 53}
    lattices_by_n: Dict[int, List[FinitePoset]] = {}
    for n in range(1, 8):
        lats = generate_unlabeled_lattices(n)
        lattices_by_n[n] = lats
        assert len(lats) == expected_oeis_a006966[n], (
            f"Count mismatch at n={n}: got {len(lats)}, expected {expected_oeis_a006966[n]}"
        )
    print(
        "[PASS] Unlabeled finite lattice counts for 1 <= |L| <= 7 match OEIS A006966: "
        + ", ".join(f"n={n}:{len(lattices_by_n[n])}" for n in range(1, 8))
    )

    # 2. Verify general Galois connection identities and non-invertibility on posets
    C1 = make_chain(1)
    C2 = make_chain(2)
    C3 = make_chain(3)
    B2 = make_boolean(2)
    B3 = make_boolean(3)
    A2 = make_antichain(2)

    test_posets = [C1, C2, C3, B2, A2] + lattices_by_n[5]
    total_gc_checked = 0
    non_bijective_gc_count = 0
    naive_swap_failures = 0

    for P in [C1, C2, C3, B2, A2]:
        for Q in [C1, C2, C3, B2, A2]:
            gcs = enumerate_galois_connections(P, Q)
            f_all = monotone_maps(P, Q)
            g_all = monotone_maps(Q, P)

            # Check unit-counit characterization equivalence on all monotone pairs
            for f in f_all:
                for g in g_all:
                    adj_ok = is_galois_connection(P, Q, f, g)
                    unit_counit_ok = all(
                        P.leq[x][g[f[x]]] for x in range(P.n)
                    ) and all(Q.leq[f[g[y]]][y] for y in range(Q.n))
                    assert adj_ok == unit_counit_ok

            # Check uniqueness of right adjoint g given f
            seen_f: Dict[Tuple[int, ...], Tuple[int, ...]] = {}
            for f, g in gcs:
                if f in seen_f:
                    assert seen_f[f] == g
                seen_f[f] = g
                total_gc_checked += 1

                # Generalized inverse laws: f o g o f = f, g o f o g = g
                for x in range(P.n):
                    assert f[g[f[x]]] == f[x]
                for y in range(Q.n):
                    assert g[f[g[y]]] == g[y]

                # Closed elements Fix(g o f) == Im(g); open elements Fix(f o g) == Im(f)
                im_g = {g[y] for y in range(Q.n)}
                fix_gf = {x for x in range(P.n) if g[f[x]] == x}
                assert im_g == fix_gf

                im_f = {f[x] for x in range(P.n)}
                fix_fg = {y for y in range(Q.n) if f[g[y]] == y}
                assert im_f == fix_fg
                assert len(im_g) == len(im_f)

                # Dual Galois connection (g, f) : Q^op <-> P^op always holds
                assert is_galois_connection(Q.dual(), P.dual(), g, f)

                if len(im_g) < P.n or len(im_f) < Q.n:
                    non_bijective_gc_count += 1
                if not is_galois_connection(Q, P, g, f):
                    naive_swap_failures += 1

    assert non_bijective_gc_count > 0
    assert naive_swap_failures > 0
    print(
        f"[PASS] Verified {total_gc_checked} monotone Galois connections across posets: "
        f"adjunction <=> unit/counit, unique right adjoint, fgf=f, gfg=g, Im(g)=Fix(gf), "
        f"dual (g,f):Q^op<->P^op; {non_bijective_gc_count} non-invertible, "
        f"{naive_swap_failures} fail un-dualized (g,f):Q<->P."
    )

    # Check A2 = 2-element antichain has no top element and no binary meet for (0, 1)
    assert A2.meet_of_subset(()) is None
    assert A2.meet_of_subset((0, 1)) is None
    assert is_galois_connection(A2, A2, (0, 1), (0, 1))
    print(
        "[PASS] Non-lattice poset counterexample A_2: (id, id) is a monotone Galois "
        "connection, but Im(id) = A_2 has neither empty meet (top) nor binary meet 0 ^ 1."
    )

    # 3. Exhaustively test closure systems and Readings I, II, III on all finite lattices
    c3_cert = canonical_certificate(C3.leq)
    b2_cert = canonical_certificate(B2.leq)
    total_closure_systems_checked = 0

    for n in range(1, 7):
        for L in lattices_by_n[n]:
            c_systems = all_closure_systems(L)
            for C in c_systems:
                total_closure_systems_checked += 1

                # Every closure system C <= L arises as Im(g) for canonical GC L <-> C
                C_poset = subposet_from_subset(L, C)
                c_sorted = sorted(C)
                idx_map = {elem: i for i, elem in enumerate(c_sorted)}
                f_can = tuple(
                    idx_map[
                        L.meet_of_subset([c for c in c_sorted if L.leq[x][c]])  # type: ignore[arg-type]
                    ]
                    for x in range(L.n)
                )
                g_can = tuple(c_sorted)
                assert is_galois_connection(L, C_poset, f_can, g_can)
                assert frozenset(g_can) == C

                # Reading I: Brute-force all subsets B <= L generating C under arbitrary meets
                irr_M = meet_irreducibles_in_closure_system(L, C)
                assert closure_system_generated_by(L, irr_M, allow_empty_meet=True) == C

                generating_sets: List[FrozenSet[int]] = []
                for r in range(L.n + 1):
                    for sub in itertools.combinations(range(L.n), r):
                        if (
                            closure_system_generated_by(
                                L, sub, allow_empty_meet=True
                            )
                            == C
                        ):
                            generating_sets.append(frozenset(sub))

                assert irr_M in generating_sets
                for B in generating_sets:
                    assert irr_M.issubset(B), (
                        f"M(C)={irr_M} was not a subset of generator B={B}"
                    )
                min_len_I = min(len(B) for B in generating_sets)
                assert min_len_I == len(irr_M)

                # Reading III: Brute-force all subsets B <= L generating C under NONEMPTY meets
                expected_nonempty_min = irr_M | {L.top()}
                assert (
                    closure_system_generated_by(
                        L, expected_nonempty_min, allow_empty_meet=False
                    )
                    == C
                )
                for r in range(len(expected_nonempty_min)):
                    for sub in itertools.combinations(range(L.n), r):
                        assert (
                            closure_system_generated_by(
                                L, sub, allow_empty_meet=False
                            )
                            != C
                        )

                # Verify exact sharp classification of |M(C)|
                if len(C) == 1:
                    assert len(irr_M) == 0
                elif len(C) == 2:
                    assert len(irr_M) == 1
                else:
                    assert len(C) >= 3 and len(irr_M) >= 2

                # Reading II on C_poset (for |C| <= 5 to keep brute force fast and exact)
                if C_poset.n <= 5:
                    j_irreds = join_irreducibles(C_poset)
                    k_min = brute_force_min_ground_set_size(C_poset)
                    assert k_min == len(j_irreds), (
                        f"Ground-set min {k_min} != |J(C)|={len(j_irreds)} on {C_poset.name}"
                    )

    # Also check |M(L)| and |J(L)| across all 53 unlabeled lattices of size n = 7
    attaining_two_certs: Set[Tuple[int, ...]] = set()
    for n in range(1, 8):
        for L in lattices_by_n[n]:
            full_C = frozenset(range(L.n))
            m_len = len(meet_irreducibles_in_closure_system(L, full_C))
            j_len = len(join_irreducibles(L))
            if n == 1:
                assert m_len == 0 and j_len == 0
            elif n == 2:
                assert m_len == 1 and j_len == 1
            else:
                assert m_len >= 2 and j_len >= 2
            if m_len == 2:
                attaining_two_certs.add(canonical_certificate(L.leq))
            if j_len == 2:
                assert canonical_certificate(L.leq) in {c3_cert, b2_cert}

    assert attaining_two_certs == {c3_cert, b2_cert}
    print(
        f"[PASS] Exhaustively verified {total_closure_systems_checked} closure systems "
        f"(all n <= 6) and all 78 unlabeled finite lattices (n <= 7):\n"
        f"       - Unique minimum meet-generator set M(C) verified by subset search;\n"
        f"       - Minimum set-closure ground-set size |U|_min == |J(C)| verified;\n"
        f"       - |M(C)| = 0 <=> |C| = 1, |M(C)| = 1 <=> |C| = 2, |M(C)| >= 2 <=> |C| >= 3;\n"
        f"       - Exact witnesses attaining bound 2 on full lattices: C_3 and B_2 ONLY."
    )

    # 4. Explicit Counterexamples Refuting the Lower Bound 2 on Finite Lattices
    # Counterexample 1: C_1 = {0} with (id, id)
    c1_full = frozenset({0})
    assert len(meet_irreducibles_in_closure_system(C1, c1_full)) == 0 < 2
    assert brute_force_min_ground_set_size(C1) == 0 < 2
    assert len(meet_irreducibles_in_closure_system(C1, c1_full) | {C1.top()}) == 1 < 2
    assert len(c1_full) == 1 < 2

    # Counterexample 2: C_2 = {0 < 1} with bijective (id, id)
    c2_full = frozenset({0, 1})
    assert is_galois_connection(C2, C2, (0, 1), (0, 1))
    assert len(meet_irreducibles_in_closure_system(C2, c2_full)) == 1 < 2
    assert brute_force_min_ground_set_size(C2) == 1 < 2

    # Counterexample 3: Constant Galois connection on nontrivial finite lattices (C_2, C_3, B_2)
    for L in (C2, C3, B2):
        f_const = tuple(L.bot() for _ in range(L.n))
        g_const = tuple(L.top() for _ in range(L.n))
        assert is_galois_connection(L, L, f_const, g_const)
        im_const = frozenset(g_const)
        assert len(im_const) == 1 < 2
        assert len(meet_irreducibles_in_closure_system(L, im_const)) == 0 < 2
        assert (
            len(meet_irreducibles_in_closure_system(L, im_const) | {L.top()}) == 1 < 2
        )

    # Counterexample 4: Non-constant 2-closed-element Galois connection on ANY |L| >= 3 (e.g. B_2, C_3)
